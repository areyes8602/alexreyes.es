# Patrón para preservar LaTeX entre $...$ y $$...$$
LATEX_RE = re.compile(r'(\$\$[^$]+\$\$|\$[^$\n]+\$)')
# Patrón para tags HTML completos (preserva atributos como class, href, id)
HTML_TAG_RE = re.compile(r'(<[^>]+>)')


def split_preserve(text):
    """Divide el texto en segmentos: protegidos (LaTeX, HTML tag) y traducibles."""
    # Primero protegemos las matemáticas
    parts = []
    last = 0
    for m in LATEX_RE.finditer(text):
        if m.start() > last:
            parts.append(("text", text[last:m.start()]))
        parts.append(("protected", m.group(0)))
        last = m.end()
    if last < len(text):
        parts.append(("text", text[last:]))

    # Ahora dentro de los "text" preservamos las tags HTML
    result = []
    for kind, segment in parts:
        if kind == "protected":
            result.append(("protected", segment))
            continue
        sub_last = 0
        for tm in HTML_TAG_RE.finditer(segment):
            if tm.start() > sub_last:
                result.append(("text", segment[sub_last:tm.start()]))
            result.append(("protected", tm.group(0)))
            sub_last = tm.end()
        if sub_last < len(segment):
            result.append(("text", segment[sub_last:]))
    return result


def translate_text(s):
    """Aplica el glosario a un fragmento de texto."""
    for ca, es in GLOSSARY:
        s = s.replace(ca, es)
    return s


def translate_html(content):
    """Procesa el HTML completo aplicando traducción solo a los fragmentos de texto."""
    parts = split_preserve(content)
    out = []
    for kind, segment in parts:
        if kind == "protected":
            out.append(segment)
        else:
            out.append(translate_text(segment))
    return "".join(out)


def main():
    n_translated = 0
    n_skipped = 0
    for html in REPO_ROOT.rglob("*.html"):
        rel = html.relative_to(REPO_ROOT)
        if rel.parts[0] in SKIP_TOP:
            continue
        try:
            text = html.read_text(encoding="utf-8")
        except Exception:
            continue

        # Solo procesamos los que tienen lang="ca"
        m = re.search(r'<html\s+lang="([^"]+)"', text)
        if not m or m.group(1) != "ca":
            n_skipped += 1
            continue

        # Traducir contenido + cambiar lang
        new_text = translate_html(text)
        new_text = re.sub(r'<html\s+lang="ca"', '<html lang="es"', new_text, count=1)

        if new_text == text:
            n_skipped += 1
            continue

        if DRY_RUN:
            print(f"  [dry-run] {rel}")
        else:
            html.write_text(new_text, encoding="utf-8")
            print(f"  ✓ {rel}")
        n_translated += 1

    print("")
    print("─── Resumen ───")
    if DRY_RUN:
        print(f"  [dry-run] Habría traducido: {n_translated}")
    else:
        print(f"  ✓ Traducidos: {n_translated}")
    print(f"  · Saltados: {n_skipped}")


if __name__ == "__main__":
    main()
