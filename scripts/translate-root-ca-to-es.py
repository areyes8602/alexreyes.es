    (" o ", " o "),  # igual
    (" o, ", " o, "),  # igual
    # Otros comunes
    ("Recordatori", "Recordatorio"),
    ("recordatori", "recordatorio"),
    ("Drecera", "Atajo"),
    ("drecera", "atajo"),
